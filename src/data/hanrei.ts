// 和暦（昭和・平成・令和）。昭和は1926/12/25〜1989/1/7、平成は1989/1/8〜2019/4/30
function era(iso: string): [string, number] {
  const [y] = iso.split('-').map(Number);
  if (iso >= '2019-05-01') return ['令和', y - 2018];
  if (iso >= '1989-01-08') return ['平成', y - 1988];
  return ['昭和', y - 1925];
}
export function hanreiWareki(iso: string) {
  const [, m, d] = iso.split('-').map(Number);
  const [name, n] = era(iso);
  return `${name}${n === 1 ? '元' : n}年${m}月${d}日`;
}
// 年の見出し（例：平成7年（1995年））
export const hanreiNen = (iso: string) => {
  const [name, n] = era(iso);
  return `${name}${n === 1 ? '元' : n}年（${iso.slice(0, 4)}年）`;
};
export const hanreiTitle = (h: Hanrei) => `${shortCourt(h)} ${hanreiWareki(h.date)} ${h.kind}`;
